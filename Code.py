def build_table(results_df, model_name, conditions, tickers):
    rows = []
    for cond in conditions:
        t_list = (CFG['tickers_c3']
                  if cond == 'C3' else tickers)
        for ticker in t_list:
            row = results_df[
                (results_df['ticker']    == ticker) &
                (results_df['condition'] == cond) &
                (results_df['model']     == model_name)]
            if len(row) == 0:
                continue
            rows.append({
                'Condition': cond, 'Ticker': ticker,
                'Accuracy':  row['accuracy'].values[0],
                'ROC-AUC':   row['roc_auc'].values[0],
                'F1':        row['f1_weighted'].values[0],
                'Model':     model_name,
            })
    return pd.DataFrame(rows)

