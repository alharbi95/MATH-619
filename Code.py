def load_file(path):
    df = pd.read_excel(path)
    df = df.rename(columns=RENAME_MAP)
    if 'Date' not in df.columns:
        date_candidates = [c for c in df.columns
                           if 'date' in c.lower() or 'time' in c.lower()]
        if date_candidates:
            df = df.rename(columns={date_candidates[0]: 'Date'})
    df['Date'] = pd.to_datetime(df['Date'])
    df = df.sort_values('Date').reset_index(drop=True)
    return df


def load_all(data_path):
    data = {}
    for ticker in TICKERS:
        path_t = find_file(data_path, ticker, 'T')
        path_s = find_file(data_path, ticker, 'S')
        data[ticker] = {
            'T': load_file(path_t),
            'S': load_file(path_s),
            'path_T': path_t,
            'path_S': path_s,
        }
        print(f"  {ticker}  T: {data[ticker]['T'].shape}  "
              f"S: {data[ticker]['S'].shape}  "
              f"[{os.path.basename(path_t)}, "
              f"{os.path.basename(path_s)}]")
    return data


