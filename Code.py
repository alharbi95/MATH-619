# ── Walk-forward fold constructor — identical to Run 3 ────────

def make_wf_folds(X_all, y_all, n_folds=4, min_train=504):
    n     = len(X_all)
    step  = (n - min_train) // n_folds
    folds = []
    for f in range(n_folds):
        train_end = min_train + f * step
        val_start = train_end
        val_end   = min(train_end + step, n)
        if val_end <= val_start:
            continue
        folds.append((
            X_all[:train_end], y_all[:train_end],
            X_all[val_start:val_end], y_all[val_start:val_end],
        ))
    return folds


def train_wf_model(builder, input_shape, arrays,
                   ticker, model_name, condition):
    """Walk-forward training protocol — identical to Run 3."""
    X_all = np.concatenate([
        arrays['X_train'], arrays['X_val']], axis=0)
    y_all = np.concatenate([
        arrays['y_train'], arrays['y_val']], axis=0)
    n_pos = y_all.sum()
    n_neg = len(y_all) - n_pos
    cw    = {0: len(y_all)/(2*n_neg) if n_neg > 0 else 1.0,
             1: len(y_all)/(2*n_pos) if n_pos > 0 else 1.0}

    folds = make_wf_folds(
        X_all, y_all,
        n_folds=CFG['n_folds'],
        min_train=max(200, len(X_all)//(CFG['n_folds']+1)))

    fold_info   = []
    fold_losses = []
    best_epochs = []

    for fold_idx, (X_tr, y_tr, X_va, y_va) in enumerate(folds):
        tf.random.set_seed(SEED + fold_idx)
        np.random.seed(SEED + fold_idx)
        model = builder(input_shape, model_name)
        cb = [
            callbacks.EarlyStopping(
                monitor='val_loss', patience=CFG['patience'],
                restore_best_weights=True, verbose=0),
            callbacks.ReduceLROnPlateau(
                monitor='val_loss', factor=0.5, patience=10,
                min_lr=1e-7, verbose=0),
        ]
        hist = model.fit(
            X_tr, y_tr,
            validation_data=(X_va, y_va),
            epochs=CFG['epochs'],
            batch_size=CFG['batch_size'],
            class_weight=cw,
            callbacks=cb, verbose=0)
        best_ep   = int(np.argmin(hist.history['val_loss'])) + 1
        best_loss = min(hist.history['val_loss'])
        best_acc  = hist.history['val_accuracy'][best_ep - 1]
        best_epochs.append(best_ep)
        fold_losses.append(hist.history['val_loss'])
        fold_info.append({
            'fold':          fold_idx + 1,
            'train_size':    len(X_tr),
            'val_size':      len(X_va),
            'best_epoch':    best_ep,
            'best_val_loss': round(best_loss, 4),
            'best_val_acc':  round(best_acc,  4),
        })
        del model

    vote_epochs = [best_epochs[i]
                   for i in CFG['epoch_vote_folds']
                   if i < len(best_epochs)]
    optimal_ep  = int(np.ceil(np.mean(vote_epochs))) + 2
    optimal_ep  = min(optimal_ep, CFG['epochs'])

    print(f"    [{ticker} {condition} {model_name}] "
          f"vote={vote_epochs}  optimal={optimal_ep}")

    tf.random.set_seed(SEED); np.random.seed(SEED)
    final_model = builder(input_shape, model_name)
    final_model.fit(
        X_all, y_all,
        epochs=optimal_ep,
        batch_size=CFG['batch_size'],
        class_weight=cw, verbose=0)

    return final_model, fold_info, optimal_ep, fold_losses


# ── Utilities ─────────────────────────────────────────────────

def evaluate_model(y_true, y_prob, ticker, condition, model_name):
    y_pred = (y_prob >= 0.5).astype(int)
    acc    = accuracy_score(y_true, y_pred)
    try:
        auc = roc_auc_score(y_true, y_prob)
    except Exception:
        auc = 0.5
    f1  = f1_score(y_true, y_pred,
                   average='weighted', zero_division=0)
    ap  = average_precision_score(y_true, y_prob)
    cm  = confusion_matrix(y_true, y_pred)
    return {
        'ticker': ticker, 'condition': condition,
        'model': model_name,
        'accuracy':      round(acc, 4),
        'roc_auc':       round(auc, 4),
        'f1_weighted':   round(f1,  4),
        'avg_precision': round(ap,  4),
        'y_true': y_true, 'y_prob': y_prob,
        'y_pred': y_pred, 'conf_matrix': cm,
    }


def train_classical(arrays, ticker, condition):
    X_tr_f  = arrays['X_train'].reshape(len(arrays['X_train']), -1)
    X_val_f = arrays['X_val'].reshape(len(arrays['X_val']),   -1)
    X_te_f  = arrays['X_test'].reshape(len(arrays['X_test']),  -1)
    X_all_f = np.concatenate([X_tr_f, X_val_f])
    y_all   = np.concatenate([arrays['y_train'], arrays['y_val']])
    y_te    = arrays['y_test']
    n_neg   = (y_all == 0).sum(); n_pos = (y_all == 1).sum()
    scale_pos = n_neg / n_pos if n_pos > 0 else 1.0
    results, models = [], {}

    lr_clf = LogisticRegression(
        max_iter=2000, C=0.1, class_weight='balanced',
        random_state=SEED, n_jobs=-1)
    lr_clf.fit(X_all_f, y_all)
    prob = lr_clf.predict_proba(X_te_f)[:, 1]
    results.append(evaluate_model(
        y_te, prob, ticker, condition, 'Logistic Regression'))

    rf = RandomForestClassifier(
        n_estimators=CFG['rf_trees'], max_depth=CFG['rf_depth'],
        class_weight='balanced', random_state=SEED, n_jobs=-1)
    rf.fit(X_all_f, y_all)
    prob = rf.predict_proba(X_te_f)[:, 1]
    results.append(evaluate_model(
        y_te, prob, ticker, condition, 'Random Forest'))

    xgb_clf = xgb.XGBClassifier(
        n_estimators=CFG['xgb_trees'], max_depth=CFG['xgb_depth'],
        learning_rate=CFG['xgb_lr'], scale_pos_weight=scale_pos,
        eval_metric='logloss', use_label_encoder=False,
        random_state=SEED, verbosity=0)
    xgb_clf.fit(X_all_f, y_all)
    prob = xgb_clf.predict_proba(X_te_f)[:, 1]
    results.append(evaluate_model(
        y_te, prob, ticker, condition, 'XGBoost'))
    return results, models

