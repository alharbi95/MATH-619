def train_dl_model(model, arrays, ticker, model_name):
    """
    Train a Keras model with early stopping and LR reduction.

    Early stopping monitors val_loss with restore_best_weights=True,
    preventing over-fitting without requiring a fixed epoch count.
    Reference: Prechelt (1998)

    ReduceLROnPlateau halves the learning rate when val_loss
    stagnates for 7 consecutive epochs.
    """
    X_tr = arrays['X_train']
    y_tr = arrays['y_train']
    X_va = arrays['X_val']
    y_va = arrays['y_val']
    cw   = arrays['class_weights']

    cb_list = [
        callbacks.EarlyStopping(
            monitor='val_loss',
            patience=CFG['patience'],
            restore_best_weights=True,
            verbose=0),
        callbacks.ReduceLROnPlateau(
            monitor='val_loss',
            factor=0.5,
            patience=7,
            min_lr=1e-6,
            verbose=0),
    ]

    t0      = time.time()
    history = model.fit(
        X_tr, y_tr,
        validation_data=(X_va, y_va),
        epochs=CFG['epochs'],
        batch_size=CFG['batch_size'],
        class_weight=cw,
        callbacks=cb_list,
        verbose=0)
    elapsed = time.time() - t0
    best_ep = int(np.argmin(history.history['val_loss'])) + 1
    val_acc = history.history['val_accuracy'][best_ep - 1]
    print(f"    [{ticker} {model_name}] "
          f"best_epoch={best_ep:3d}  "
          f"val_loss={min(history.history['val_loss']):.4f}  "
          f"val_acc={val_acc:.4f}  "
          f"time={elapsed:.0f}s")
    return model, history


def evaluate_model(y_true, y_prob, ticker, condition, model_name):
    """
    Compute evaluation metrics for one model on the test set.

    Metrics reported:
      accuracy       — directional correctness (primary metric)
      roc_auc        — threshold-independent discriminative power
      f1_weighted    — harmonic mean of precision/recall (weighted)
      avg_precision  — area under precision-recall curve
    """
    y_pred = (y_prob >= 0.5).astype(int)
    acc    = accuracy_score(y_true, y_pred)
    try:
        auc = roc_auc_score(y_true, y_prob)
    except Exception:
        auc = 0.5
    f1  = f1_score(y_true, y_pred,
                   average='weighted', zero_division=0)
    ap  = average_precision_score(y_true, y_prob)
    cm  = confusion_matrix(y_true, y_pred)
    return {
        'ticker':        ticker,
        'condition':     condition,
        'model':         model_name,
        'accuracy':      round(acc,  4),
        'roc_auc':       round(auc,  4),
        'f1_weighted':   round(f1,   4),
        'avg_precision': round(ap,   4),
        'y_true':        y_true,
        'y_prob':        y_prob,
        'y_pred':        y_pred,
        'conf_matrix':   cm,
    }


def train_classical(arrays, ticker, condition):
    """
    Train LR, RF, and XGBoost on flattened sequences.

    Classical models require 2D input (samples, features).
    The 3D sequence (samples, look_back, n_features) is flattened
    to (samples, look_back × n_features).
    This is standard practice when comparing sequence models
    against classical methods on identical features.
    Reference: Fischer & Krauss (2018); Gu et al. (2020)
    """
    X_tr_f = arrays['X_train'].reshape(len(arrays['X_train']), -1)
    X_te_f = arrays['X_test'].reshape(len(arrays['X_test']),   -1)
    y_tr   = arrays['y_train']
    y_te   = arrays['y_test']
    n_neg  = (y_tr == 0).sum()
    n_pos  = (y_tr == 1).sum()
    scale_pos = n_neg / n_pos if n_pos > 0 else 1.0

    results = []
    models  = {}

    # Logistic Regression — linear baseline.
    # Expected to perform near majority-class baseline because
    # no feature has meaningful linear predictive power
    # (max |corr| = 0.045, DU-6). C=0.1 applies L2 regularisation.
    lr = LogisticRegression(
            max_iter=2000, C=0.1,
            class_weight='balanced',
            random_state=SEED, n_jobs=-1)
    lr.fit(X_tr_f, y_tr)
    prob = lr.predict_proba(X_te_f)[:, 1]
    results.append(evaluate_model(
        y_te, prob, ticker, condition, 'Logistic Regression'))
    models['Logistic Regression'] = lr

    # Random Forest — non-linear ensemble baseline.
    # Reference: Khaidem et al. (2016)
    rf = RandomForestClassifier(
            n_estimators=CFG['rf_trees'],
            max_depth=CFG['rf_depth'],
            class_weight='balanced',
            random_state=SEED, n_jobs=-1)
    rf.fit(X_tr_f, y_tr)
    prob = rf.predict_proba(X_te_f)[:, 1]
    results.append(evaluate_model(
        y_te, prob, ticker, condition, 'Random Forest'))
    models['Random Forest'] = rf

    # XGBoost — gradient boosting baseline.
    # Reference: Chen & Guestrin (2016)
    xgb_clf = xgb.XGBClassifier(
            n_estimators=CFG['xgb_trees'],
            max_depth=CFG['xgb_depth'],
            learning_rate=CFG['xgb_lr'],
            scale_pos_weight=scale_pos,
            eval_metric='logloss',
            use_label_encoder=False,
            random_state=SEED,
            verbosity=0)
    xgb_clf.fit(X_tr_f, y_tr)
    prob = xgb_clf.predict_proba(X_te_f)[:, 1]
    results.append(evaluate_model(
        y_te, prob, ticker, condition, 'XGBoost'))
    models['XGBoost'] = xgb_clf

    return results, models


