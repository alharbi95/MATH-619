def train_wf_model(builder, input_shape, arrays,
                   ticker, model_name, condition):
    X_all = np.concatenate([
        arrays['X_train'], arrays['X_val']], axis=0)
    y_all = np.concatenate([
        arrays['y_train'], arrays['y_val']], axis=0)
    n_pos = y_all.sum()
    n_neg = len(y_all) - n_pos
    cw    = {0: len(y_all)/(2*n_neg) if n_neg > 0 else 1.0,
             1: len(y_all)/(2*n_pos) if n_pos > 0 else 1.0}

    folds = make_wf_folds(
        X_all, y_all,
        n_folds=CFG['n_folds'],
        min_train=max(200, len(X_all)//(CFG['n_folds']+1)))

    fold_info   = []
    fold_losses = []
    best_epochs = []

    for fold_idx, (X_tr, y_tr, X_va, y_va) in enumerate(folds):
        tf.random.set_seed(SEED + fold_idx)
        np.random.seed(SEED + fold_idx)
        model = builder(input_shape, model_name)
        cb = [
            callbacks.EarlyStopping(
                monitor='val_loss', patience=CFG['patience'],
                restore_best_weights=True, verbose=0),
            callbacks.ReduceLROnPlateau(
                monitor='val_loss', factor=0.5, patience=10,
                min_lr=1e-7, verbose=0),
        ]
        hist = model.fit(
            X_tr, y_tr,
            validation_data=(X_va, y_va),
            epochs=CFG['epochs'],
            batch_size=CFG['batch_size'],
            class_weight=cw,
            callbacks=cb, verbose=0)
        best_ep   = int(np.argmin(hist.history['val_loss'])) + 1
        best_loss = min(hist.history['val_loss'])
        best_acc  = hist.history['val_accuracy'][best_ep - 1]
        best_epochs.append(best_ep)
        fold_losses.append(hist.history['val_loss'])
        fold_info.append({
            'fold':          fold_idx + 1,
            'train_size':    len(X_tr),
            'val_size':      len(X_va),
            'best_epoch':    best_ep,
            'best_val_loss': round(best_loss, 4),
            'best_val_acc':  round(best_acc,  4),
            'used_in_vote':  fold_idx in CFG['epoch_vote_folds'],
        })
        del model

    vote_epochs = [best_epochs[i]
                   for i in CFG['epoch_vote_folds']
                   if i < len(best_epochs)]
    optimal_ep  = int(np.ceil(np.mean(vote_epochs))) + 2
    optimal_ep  = min(optimal_ep, CFG['epochs'])

    print(f"    [{ticker} {condition} {model_name}] "
          f"all_folds={str(best_epochs)}  "
          f"vote_folds={str(vote_epochs)}  "
          f"optimal={optimal_ep}")

    tf.random.set_seed(SEED); np.random.seed(SEED)
    final_model = builder(input_shape, model_name)
    final_model.fit(
        X_all, y_all,
        epochs=optimal_ep,
        batch_size=CFG['batch_size'],
        class_weight=cw, verbose=0)

    return final_model, fold_info, optimal_ep, fold_losses


