# ── E1 — Diebold-Mariano Tests ────────────────────────────────
# Compares best model per condition against all baselines.
# Uses 0-1 loss (misclassification) and Harvey et al. (1997)
# small-sample correction. H0: equal predictive accuracy.
# Reference: Diebold & Mariano (1995, JBES)

def dm_test(y_true, prob1, prob2, h=1):
    """
    Diebold-Mariano test for equal predictive accuracy.
    prob1 = baseline probabilities, prob2 = proposed model.
    Negative DM stat: baseline has lower loss (baseline better).
    Reference: Harvey, Leybourne & Newbold (1997, IJF)
    """
    pred1  = (prob1 >= 0.5).astype(int)
    pred2  = (prob2 >= 0.5).astype(int)
    e1     = (pred1 != y_true).astype(float)
    e2     = (pred2 != y_true).astype(float)
    d      = e1 - e2
    T      = len(d)
    d_bar  = d.mean()
    gamma0 = np.var(d, ddof=1)
    if gamma0 < 1e-12:
        return 0.0, 1.0
    hac    = np.sqrt((T + 1 - 2*h + h*(h-1)/T) / T)
    dm_raw = d_bar / np.sqrt(gamma0 / T)
    dm_hc  = dm_raw * hac
    p_val  = 2 * scipy_stats.t.sf(abs(dm_hc), df=T-1)
    return round(dm_hc, 4), round(p_val, 4)


