def sent_analysis(ticker):
    df = DATA[ticker]['S'].copy()
    if 'Sentiment' not in df.columns:
        print(f"  {ticker}: No sentiment column found.")
        return None
    s  = df['Sentiment']
    y  = compute_target(df).reindex(df.index)
    df['y'] = y
    return {
        'ticker':           ticker,
        'mean':             s.mean(),
        'std':              s.std(),
        'min':              s.min(),
        'max':              s.max(),
        'skew':             stats.skew(s.dropna()),
        'autocorr_1d':      s.autocorr(lag=1),
        'autocorr_5d':      s.autocorr(lag=5),
        'near_zero%':       (s.abs() < 0.05).mean() * 100,
        'strong_pos%':      (s > 0.20).mean() * 100,
        'strong_neg%':      (s < -0.20).mean() * 100,
        'corr_w_direction': s.corr(df['y'].fillna(0)),
    }


