# ── Steps 5–7 — Scaling, sequence construction, output arrays

def make_sequences(X_scaled, y, look_back):
    """
    Sliding window sequence builder.
    X[i] = rows i to i+look_back-1   shape: (look_back, n_features)
    y[i] = label at row i+look_back
    Causal: no future information enters the input window.
    Reference: Lu et al. (2020); Nelson et al. (2017)
    """
    Xs, ys = [], []
    for i in range(len(X_scaled) - look_back):
        Xs.append(X_scaled[i: i + look_back])
        ys.append(y[i + look_back])
    return (np.array(Xs, dtype=np.float32),
            np.array(ys, dtype=np.int32))


def prepare_condition(ticker, condition):
    """
    Full pipeline: split -> inject C3 sentiment -> scale -> sequences.

    C3 two-stage scaler design:
      Stage A — non-Sentiment features scaled using train rows only.
      Stage B — Sentiment scaled using (S) file real values, so the
                scaler's mean/variance reflects actual test-window
                sentiment rather than the training zero-fill.
      Stage C — both scalers merged into one unified StandardScaler
                for consistent downstream inference.

    Returns
    -------
    arrays : dict — X/y for train, val, test + class_weights
    scaler : unified fitted StandardScaler
    info   : metadata dict for thesis summary table
    """
    features  = FEATURE_SETS[condition]
    is_c3     = (condition == 'C3')
    look_back = CFG['look_back']

    df_tr, df_va, df_te, split_info = temporal_split(
        DATA[ticker]['T'], DATA[ticker]['S'])

    # C3: inject Sentiment = 0.0 into (T)-sourced train/val rows.
    # The model sees a neutral prior during training and learns
    # to weight the real signal at test time.
    if is_c3:
        df_tr = df_tr.copy()
        df_va = df_va.copy()
        if 'Sentiment' not in df_tr.columns:
            df_tr['Sentiment'] = 0.0
        if 'Sentiment' not in df_va.columns:
            df_va['Sentiment'] = 0.0
        assert 'Sentiment' in df_te.columns, \
            f"[{ticker} C3] (S) file missing Sentiment column"

    # Validate all required features are present
    for sname, df in [('train', df_tr), ('val', df_va),
                      ('test', df_te)]:
        missing = [f for f in features if f not in df.columns]
        if missing:
            raise ValueError(
                f"[{ticker} {condition}] Missing in {sname}: {missing}")

    # Extract raw arrays
    X_tr_raw = df_tr[features].values.astype(np.float32)
    X_va_raw = df_va[features].values.astype(np.float32)
    X_te_raw = df_te[features].values.astype(np.float32)
    y_tr     = df_tr['y'].values.astype(np.int32)
    y_va     = df_va['y'].values.astype(np.int32)
    y_te     = df_te['y'].values.astype(np.int32)

    # Scaling
    if not is_c3:
        scaler  = StandardScaler()
        X_tr_sc = scaler.fit_transform(X_tr_raw)
        X_va_sc = scaler.transform(X_va_raw)
        X_te_sc = scaler.transform(X_te_raw)

    else:
        sent_idx     = features.index('Sentiment')
        non_sent_idx = [i for i in range(len(features))
                        if i != sent_idx]

        sc_main = StandardScaler()
        sc_main.fit(X_tr_raw[:, non_sent_idx])

        sc_sent = StandardScaler()
        sc_sent.fit(df_te[['Sentiment']].values.astype(np.float32))

        n      = len(features)
        mean_  = np.zeros(n, dtype=np.float64)
        scale_ = np.ones(n,  dtype=np.float64)
        var_   = np.ones(n,  dtype=np.float64)

        mean_[non_sent_idx]  = sc_main.mean_
        scale_[non_sent_idx] = sc_main.scale_
        var_[non_sent_idx]   = sc_main.var_

        mean_[sent_idx]  = float(sc_sent.mean_[0])
        scale_[sent_idx] = float(sc_sent.scale_[0])
        var_[sent_idx]   = float(sc_sent.var_[0])

        scaler = StandardScaler()
        scaler.mean_           = mean_
        scaler.scale_          = scale_
        scaler.var_            = var_
        scaler.n_features_in_  = n
        scaler.n_samples_seen_ = len(X_tr_raw)

        X_tr_sc = scaler.transform(X_tr_raw)
        X_va_sc = scaler.transform(X_va_raw)
        X_te_sc = scaler.transform(X_te_raw)

        s_tr = X_tr_sc[:, sent_idx]
        s_te = X_te_sc[:, sent_idx]
        print(f"    [{ticker} C3] Sentiment z-scores: "
              f"train mean={s_tr.mean():+.4f} std={s_tr.std():.6f}  "
              f"test mean={s_te.mean():+.4f} std={s_te.std():.4f}")

    # Sequence construction
    X_train, y_train = make_sequences(X_tr_sc, y_tr, look_back)
    X_val,   y_val   = make_sequences(X_va_sc, y_va, look_back)
    X_test,  y_test  = make_sequences(X_te_sc, y_te, look_back)

    # Class weights correct for the bull-bias in training distribution
    cw = compute_class_weight('balanced',
                              classes=np.array([0, 1]),
                              y=y_train)
    class_weights = {0: float(cw[0]), 1: float(cw[1])}

    arrays = dict(
        X_train=X_train, y_train=y_train,
        X_val=X_val,     y_val=y_val,
        X_test=X_test,   y_test=y_test,
        class_weights=class_weights,
    )

    info = {
        **split_info,
        'ticker':        ticker,
        'condition':     condition,
        'n_features':    len(features),
        'features':      features,
        'X_train_shape': X_train.shape,
        'X_val_shape':   X_val.shape,
        'X_test_shape':  X_test.shape,
        'class_weights': class_weights,
        'y_train_up%':   float(y_train.mean() * 100),
        'y_val_up%':     float(y_val.mean()   * 100),
        'y_test_up%':    float(y_test.mean()  * 100),
    }

    return arrays, scaler, info


