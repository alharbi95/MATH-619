# GOOG(S) has 14 missing Sentiment values (confirmed in DU-1).
# Forward-fill within the (S) file only — no cross-boundary fill.
# Justification: missing = no tweets collected that day, not
# neutral sentiment. ffill is causally valid (uses only t-1).

def impute_sentiment(df, ticker):
    if 'Sentiment' not in df.columns:
        return df
    before = df['Sentiment'].isnull().sum()
    if before == 0:
        return df
    df = df.copy()
    df['Sentiment'] = df['Sentiment'].ffill()
    df['Sentiment'] = df['Sentiment'].bfill()
    after = df['Sentiment'].isnull().sum()
    print(f"  [{ticker}(S)] Sentiment NaN: {before} -> {after}  "
          f"{'OK' if after == 0 else 'PROBLEM'}")
    assert after == 0, \
        f"Imputation failed: {after} NaN remain in {ticker} Sentiment"
    return df


