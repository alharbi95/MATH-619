def build_cnn_lstm(input_shape, name='CNN-LSTM'):
    reg = regularizers.l2(CFG['l2_reg'])
    inp = layers.Input(shape=input_shape)
    x   = layers.Conv1D(CFG['cnn_filters'], CFG['cnn_kernel'],
                        padding='causal', activation='relu',
                        kernel_regularizer=reg)(inp)
    x   = layers.MaxPooling1D(pool_size=2)(x)
    x   = layers.Dropout(CFG['dropout'])(x)
    x   = layers.LSTM(CFG['lstm_units'],
                      kernel_regularizer=reg,
                      recurrent_regularizer=reg)(x)
    x   = layers.BatchNormalization()(x)
    x   = layers.Dropout(CFG['dropout'])(x)
    x   = layers.Dense(32, activation='relu',
                       kernel_regularizer=reg)(x)
    out = layers.Dense(1, activation='sigmoid')(x)
    m   = keras.Model(inp, out, name=name)
    m.compile(
        optimizer=Adam(CFG['learning_rate'],
                       clipnorm=CFG['clip_norm']),
        loss='binary_crossentropy', metrics=['accuracy'])
    return m


