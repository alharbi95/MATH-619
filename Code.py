# ── Walk-forward fold constructor ─────────────────────────────
# Creates 4 expanding-window folds from the pre-test training data.
# Each fold adds one more year to the training set and validates
# on the following year. This ensures early stopping decisions are
# made on val windows covering 2017, 2018, 2019, and 2020 —
# four distinct market regimes — rather than a single COVID window.

def make_wf_folds(X_all, y_all, n_folds=4, min_train=504):
    """
    Build n_folds expanding walk-forward folds.

    Parameters
    ----------
    X_all     : scaled feature array (n_total, look_back, n_feat)
    y_all     : label array (n_total,)
    n_folds   : number of folds
    min_train : minimum training samples in fold 1

    Returns
    -------
    List of (X_train, y_train, X_val, y_val) tuples.
    """
    n    = len(X_all)
    step = (n - min_train) // n_folds
    folds = []
    for f in range(n_folds):
        train_end = min_train + f * step
        val_start = train_end
        val_end   = min(train_end + step, n)
        if val_end <= val_start:
            continue
        folds.append((
            X_all[:train_end], y_all[:train_end],
            X_all[val_start:val_end], y_all[val_start:val_end],
        ))
    return folds


