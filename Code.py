# ── Model builders ────────────────────────────────────────────
#
# CNN-LSTM ARCHITECTURE:
#   Conv1D (causal padding): extracts local temporal patterns from
#     the look_back window. Causal padding ensures no future
#     timestep is visible to earlier positions.
#     Reference: Sezer & Ozbayoglu (2018)
#   MaxPooling1D: reduces temporal dimensionality, prevents the
#     LSTM from over-fitting to fine-grained noise.
#   LSTM: captures long-range sequential dependencies across the
#     compressed representation.
#     Reference: Fischer & Krauss (2018)
#   BatchNormalization: stabilises training, mild regulariser.
#     Reference: Ioffe & Szegedy (2015)
#   Dropout: prevents co-adaptation of hidden units.
#     Reference: Srivastava et al. (2014)
#   L2 weight decay: additional regularisation for small datasets.
#     Reference: Goodfellow et al. (2016) Ch.7
#   Sigmoid output: binary classification probability.
#
# CNN-ONLY ABLATION:
#   LSTM replaced by GlobalAveragePooling1D. Isolates the
#   contribution of sequential memory.
#   Reference: Lu et al. (2020) Table 3 ablation design.
#
# LSTM-ONLY ABLATION:
#   Conv1D and MaxPooling removed. Sequence fed directly to LSTM.
#   Isolates the contribution of local feature extraction.

def build_cnn_lstm(input_shape, name='CNN-LSTM'):
    reg = regularizers.l2(CFG['l2_reg'])
    inp = layers.Input(shape=input_shape, name='input')
    x   = layers.Conv1D(
              filters=CFG['cnn_filters'],
              kernel_size=CFG['cnn_kernel'],
              padding='causal', activation='relu',
              kernel_regularizer=reg, name='conv1d')(inp)
    x   = layers.MaxPooling1D(pool_size=2, name='maxpool')(x)
    x   = layers.Dropout(CFG['dropout'], name='drop_cnn')(x)
    x   = layers.LSTM(
              CFG['lstm_units'],
              kernel_regularizer=reg,
              recurrent_regularizer=reg, name='lstm')(x)
    x   = layers.BatchNormalization(name='bn')(x)
    x   = layers.Dropout(CFG['dropout'], name='drop_lstm')(x)
    x   = layers.Dense(32, activation='relu',
                       kernel_regularizer=reg, name='dense')(x)
    out = layers.Dense(1, activation='sigmoid', name='output')(x)
    model = keras.Model(inp, out, name=name)
    model.compile(
        optimizer=Adam(CFG['learning_rate']),
        loss='binary_crossentropy',
        metrics=['accuracy'])
    return model


def build_cnn_only(input_shape, name='CNN-only'):
    reg = regularizers.l2(CFG['l2_reg'])
    inp = layers.Input(shape=input_shape, name='input')
    x   = layers.Conv1D(
              filters=CFG['cnn_filters'],
              kernel_size=CFG['cnn_kernel'],
              padding='causal', activation='relu',
              kernel_regularizer=reg, name='conv1d')(inp)
    x   = layers.MaxPooling1D(pool_size=2, name='maxpool')(x)
    x   = layers.Dropout(CFG['dropout'], name='drop_cnn')(x)
    x   = layers.GlobalAveragePooling1D(name='gap')(x)
    x   = layers.BatchNormalization(name='bn')(x)
    x   = layers.Dropout(CFG['dropout'], name='drop_dense')(x)
    x   = layers.Dense(32, activation='relu',
                       kernel_regularizer=reg, name='dense')(x)
    out = layers.Dense(1, activation='sigmoid', name='output')(x)
    model = keras.Model(inp, out, name=name)
    model.compile(
        optimizer=Adam(CFG['learning_rate']),
        loss='binary_crossentropy',
        metrics=['accuracy'])
    return model


def build_lstm_only(input_shape, name='LSTM-only'):
    reg = regularizers.l2(CFG['l2_reg'])
    inp = layers.Input(shape=input_shape, name='input')
    x   = layers.LSTM(
              CFG['lstm_units'],
              kernel_regularizer=reg,
              recurrent_regularizer=reg, name='lstm')(inp)
    x   = layers.BatchNormalization(name='bn')(x)
    x   = layers.Dropout(CFG['dropout'], name='drop')(x)
    x   = layers.Dense(32, activation='relu',
                       kernel_regularizer=reg, name='dense')(x)
    out = layers.Dense(1, activation='sigmoid', name='output')(x)
    model = keras.Model(inp, out, name=name)
    model.compile(
        optimizer=Adam(CFG['learning_rate']),
        loss='binary_crossentropy',
        metrics=['accuracy'])
    return model


