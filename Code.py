class TemporalAttention(layers.Layer):
    """
    Single-head temporal self-attention.
    Reference: Bahdanau et al. (2015); Qin et al. (2017)
    """
    def __init__(self, units=32, **kwargs):
        super().__init__(**kwargs)
        self.units = units
        self.W = layers.Dense(units, use_bias=True,
                              activation='tanh')
        self.v = layers.Dense(1, use_bias=False)

    def call(self, hidden_states):
        score   = self.W(hidden_states)
        score   = self.v(score)
        weights = tf.nn.softmax(score, axis=1)
        context = weights * hidden_states
        return context, weights

    def get_config(self):
        config = super().get_config()
        config.update({'units': self.units})
        return config


def build_cnn_lstm(input_shape):
    reg = regularizers.l2(CFG['l2_reg'])
    inp = layers.Input(shape=input_shape)
    x   = layers.Conv1D(CFG['cnn_filters'], CFG['cnn_kernel'],
                        padding='causal', activation='relu',
                        kernel_regularizer=reg)(inp)
    x   = layers.MaxPooling1D(pool_size=2)(x)
    x   = layers.Dropout(CFG['dropout'])(x)
    x   = layers.LSTM(CFG['lstm_units'],
                      kernel_regularizer=reg,
                      recurrent_regularizer=reg)(x)
    x   = layers.BatchNormalization()(x)
    x   = layers.Dropout(CFG['dropout'])(x)
    x   = layers.Dense(32, activation='relu',
                       kernel_regularizer=reg)(x)
    out = layers.Dense(1, activation='sigmoid')(x)
    m   = keras.Model(inp, out)
    m.compile(optimizer=Adam(CFG['learning_rate'],
                             clipnorm=CFG['clip_norm']),
              loss='binary_crossentropy', metrics=['accuracy'])
    return m


def build_cnn_lstm_attn(input_shape):
    reg = regularizers.l2(CFG['l2_reg'])
    inp = layers.Input(input_shape)
    x   = layers.Conv1D(CFG['cnn_filters'], CFG['cnn_kernel'],
                        padding='causal', activation='relu',
                        kernel_regularizer=reg)(inp)
    x   = layers.MaxPooling1D(pool_size=2)(x)
    x   = layers.Dropout(CFG['dropout'])(x)
    attn_out, attn_weights = TemporalAttention(
        units=32, name='temporal_attention')(x)
    x   = layers.Add()([x, attn_out])
    x   = layers.LayerNormalization()(x)
    x   = layers.LSTM(CFG['lstm_units'],
                      kernel_regularizer=reg,
                      recurrent_regularizer=reg)(x)
    x   = layers.BatchNormalization()(x)
    x   = layers.Dropout(CFG['dropout'])(x)
    x   = layers.Dense(32, activation='relu',
                       kernel_regularizer=reg)(x)
    out = layers.Dense(1, activation='sigmoid')(x)
    m   = keras.Model(inp, out)
    m.compile(optimizer=Adam(CFG['learning_rate'],
                             clipnorm=CFG['clip_norm']),
              loss='binary_crossentropy', metrics=['accuracy'])
    return m


def retrain_model(ticker, condition, model_type, n_epochs):
    """
    Retrain on full pre-test data for n_epochs.
    model_type: 'cnn_lstm' or 'cnn_lstm_attn'
    """
    arrays    = PREPARED[ticker][condition]
    X_all     = np.concatenate([arrays['X_train'],
                                 arrays['X_val']], axis=0)
    y_all     = np.concatenate([arrays['y_train'],
                                 arrays['y_val']], axis=0)
    n_pos     = y_all.sum(); n_neg = len(y_all) - n_pos
    cw        = {0: len(y_all)/(2*n_neg) if n_neg > 0 else 1.0,
                 1: len(y_all)/(2*n_pos) if n_pos > 0 else 1.0}
