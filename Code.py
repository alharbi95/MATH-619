def find_file(data_path, ticker, kind):
    candidates = [
        f'{ticker}({kind}).xlsx',
        f'{ticker}_{kind}_.xlsx',
        f'{ticker}_{kind}.xlsx',
        f'{ticker.lower()}({kind.lower()}).xlsx',
        f'{ticker.lower()}_{kind.lower()}_.xlsx',
        f'{ticker}({kind}).xlsx'.replace('xlsx', 'XLSX'),
    ]
    for name in candidates:
        full = os.path.join(data_path, name)
        if os.path.exists(full):
            return full
    try:
        all_files = os.listdir(data_path)
        for f in all_files:
            if (ticker.upper() in f.upper() and
                    kind.upper() in f.upper() and
                    f.endswith('.xlsx')):
                return os.path.join(data_path, f)
    except Exception:
        pass
    raise FileNotFoundError(
        f"Could not find {ticker} {kind} file in {data_path}.\n"
        f"Tried: {candidates}\n"
        f"Files present: {os.listdir(data_path)}"
    )


