# ── Step 3 — Temporal split ───────────────────────────────────
# Train     : (T) rows strictly BEFORE test_start
# Validation: last val_frac of training rows (temporal, no shuffle)
# Test      : fixed 252-day (S) window — same for all conditions
#
# No shuffling at any stage. Stock forecasting is a temporal
# prediction problem; shuffling constitutes look-ahead bias.
# Reference: Prado (2018) Ch.7; Gu et al. (2020, RFS)

def temporal_split(df_T, df_S, val_frac=None):
    if val_frac is None:
        val_frac = CFG['val_frac']

    test_start    = pd.Timestamp(CFG['test_start'])
    df_train_full = df_T[df_T['Date'] < test_start].copy()
    df_test       = df_S.copy()

    # Leakage assertion — must pass before scaler is fitted
    train_max = df_train_full['Date'].max()
    test_min  = df_test['Date'].min()
    assert train_max < test_min, (
        f"LEAKAGE: train ends {train_max}, test starts {test_min}")

    n_val    = int(len(df_train_full) * val_frac)
    df_val   = df_train_full.iloc[-n_val:].copy()
    df_train = df_train_full.iloc[:-n_val].copy()

    info = {
        'train_start': df_train['Date'].min().date(),
        'train_end':   df_train['Date'].max().date(),
        'val_start':   df_val['Date'].min().date(),
        'val_end':     df_val['Date'].max().date(),
        'test_start':  df_test['Date'].min().date(),
        'test_end':    df_test['Date'].max().date(),
        'n_train':     len(df_train),
        'n_val':       len(df_val),
        'n_test':      len(df_test),
    }
    return df_train, df_val, df_test, info


