# ── Integrated Gradients implementation ───────────────────────
# Pure TF implementation — no shap library dependency.
# Mathematically equivalent to SHAP GradientExplainer.
# Reference: Sundararajan et al. (2017); Lundberg & Lee (2017).

def integrated_gradients(model, X, baseline=None,
                          n_steps=50, batch_size=32):
    """
    Compute Integrated Gradients attributions.

    For each input sample x, attributions are:
        IG(x) = (x - baseline) * mean(grad(f, alpha))
    where alpha interpolates from baseline to x over n_steps.

    Parameters
    ----------
    model      : fitted Keras model
    X          : input array (n_samples, look_back, n_feat)
    baseline   : reference input (default: zero tensor)
    n_steps    : number of interpolation steps (default 50)
    batch_size : interpolation batch size

    Returns
    -------
    attributions : array (n_samples, look_back, n_feat)
    mean_abs     : mean |attribution| per feature
    """
    X        = X.astype(np.float32)
    if baseline is None:
        baseline = np.zeros_like(X[:1], dtype=np.float32)
    else:
        baseline = baseline.astype(np.float32)

    # Interpolation steps from baseline to input
    alphas      = np.linspace(0, 1, n_steps + 1,
                               dtype=np.float32)
    all_grads   = []

    for i in range(0, len(X), batch_size):
        X_batch = X[i:i + batch_size]
        # Broadcast: (n_steps+1, batch, look_back, n_feat)
        interp  = (baseline
                   + alphas[:, None, None, None]
                   * (X_batch[None] - baseline))
        # Reshape to (n_steps+1 * batch, look_back, n_feat)
        n_s, n_b = interp.shape[0], interp.shape[1]
        interp_flat = interp.reshape(n_s * n_b,
                                     *interp.shape[2:])
        interp_tf   = tf.constant(interp_flat)

        with tf.GradientTape() as tape:
            tape.watch(interp_tf)
            preds = model(interp_tf, training=False)
        grads = tape.gradient(preds, interp_tf).numpy()
        # Reshape back to (n_steps+1, batch, look_back, n_feat)
        grads = grads.reshape(n_s, n_b, *grads.shape[1:])
        # Trapezoidal integration over steps axis
        avg_grads = np.trapz(grads, axis=0) / n_steps
        # Element-wise multiply by (x - baseline)
        delta = X_batch - baseline
        ig    = avg_grads * delta
        all_grads.append(ig)

    attributions = np.concatenate(all_grads, axis=0)
    mean_abs     = np.abs(attributions).mean(axis=(0, 1))
    return attributions, mean_abs


